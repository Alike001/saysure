import test from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { chromium } from 'playwright';
import AxeBuilder from '@axe-core/playwright';
import { demoServer } from '../src/demo-server.mjs';
test('judge fixture demo: no credentials, API calls or WebAuthn; labelled simulated choices and accessible help', { timeout: 60000 }, async t => {
  const server = demoServer(); server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  t.after(async () => { await browser.close(); await new Promise(resolve => { server.close(resolve); server.closeAllConnections(); }); });
  const context = await browser.newContext(), page = await context.newPage();
  const origin = `http://localhost:${server.address().port}`, traffic = [], errors = [];
  await page.addInitScript(() => { navigator.credentials.create = navigator.credentials.get = () => { throw new Error('Demo must not call WebAuthn'); }; });
  await context.route('**/*', route => { const req = route.request(); traffic.push({ url: req.url(), method: req.method() });
    return new URL(req.url()).origin === origin ? route.continue() : route.abort(); });
  page.on('pageerror', error => errors.push(error.message)); await page.goto(origin);
  await page.getByText('DEMO ONLY — deterministic fixtures.', { exact: false }).waitFor();
  const approval = page.getByRole('button', { name: 'Simulate local consent approval', exact: true });
  await approval.focus(); await page.keyboard.press('Enter');
  await page.locator('#message').filter({ hasText: 'SIMULATED consent approval only' }).waitFor();
  await page.getByRole('button', { name: 'Change fixture quantity', exact: false }).click();
  await page.getByText('Revision: 2. Simulated local consent: pending.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'MOCK PayPal order', exact: true }).click();
  await page.getByText('MOCK PayPal fixture / no authenticated API response', { exact: false }).waitFor();
  await page.getByLabel('Choose a buyer question').selectOption('merchant');
  await page.getByRole('button', { name: 'Explain selected question', exact: true }).click();
  await page.locator('#explanation').filter({ hasText: 'helper-provided fixture' }).waitFor();
  await page.getByRole('button', { name: 'Simulate decline', exact: true }).click();
  assert.equal(await approval.isDisabled(), true);
  await page.getByRole('button', { name: 'Synthetic request', exact: true }).click(); await approval.click();
  await page.getByRole('button', { name: 'Simulate consuming consent once', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Simulate consuming consent once', exact: true }).isDisabled(), true);
  await page.setViewportSize({ width: 320, height: 900 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.deepEqual((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()).violations.map(v => v.id), []);
  assert.deepEqual(errors, []); assert.deepEqual(await context.cookies(), []);
  assert.ok(traffic.every(r => r.method === 'GET' && new URL(r.url).origin === origin && !new URL(r.url).pathname.startsWith('/api')));
  assert.equal((await fetch(`${origin}/api/requests`)).status, 404);
  assert.equal((await fetch(`${origin}/`, { method: 'POST' })).status, 404);
  assert.equal((await fetch(`${origin}/.env`)).status, 404);
});
