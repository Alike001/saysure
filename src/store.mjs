import { DatabaseSync } from 'node:sqlite';
import { Pool, types } from 'pg';
import { ensure } from './core.mjs';

const postgresSchema = `
CREATE TABLE IF NOT EXISTS schema_migrations (
  version INTEGER PRIMARY KEY,
  applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY,
  role TEXT NOT NULL CHECK (role IN ('helper','buyer')),
  salt TEXT NOT NULL,
  password_hash TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS trial_invites (
  token_hash TEXT PRIMARY KEY,
  helper_id TEXT NOT NULL REFERENCES users(id),
  buyer_id TEXT NOT NULL UNIQUE REFERENCES users(id),
  expires BIGINT NOT NULL,
  claimed BIGINT
);
CREATE TABLE IF NOT EXISTS credentials (
  id TEXT PRIMARY KEY,
  buyer_id TEXT NOT NULL UNIQUE REFERENCES users(id),
  public_key BYTEA NOT NULL,
  counter BIGINT NOT NULL,
  transports TEXT NOT NULL,
  device_type TEXT NOT NULL,
  backed_up SMALLINT NOT NULL CHECK (backed_up IN (0,1))
);
CREATE TABLE IF NOT EXISTS sessions (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id),
  csrf TEXT NOT NULL,
  expires BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS requests (
  id TEXT PRIMARY KEY,
  helper_id TEXT NOT NULL REFERENCES users(id),
  buyer_id TEXT NOT NULL REFERENCES users(id),
  snapshot TEXT NOT NULL,
  digest TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('pending','approved','rejected','withdrawn','expired','consumed','invalidated')),
  consent_digest TEXT,
  consumed_at BIGINT,
  created_at BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL
);
CREATE TABLE IF NOT EXISTS challenges (
  id TEXT PRIMARY KEY,
  session_id TEXT NOT NULL,
  buyer_id TEXT NOT NULL,
  kind TEXT NOT NULL,
  request_id TEXT,
  digest TEXT,
  challenge TEXT NOT NULL,
  expires BIGINT NOT NULL,
  used INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS paypal_bindings (
  request_id TEXT PRIMARY KEY REFERENCES requests(id),
  order_id TEXT NOT NULL UNIQUE,
  observed_at BIGINT NOT NULL,
  available SMALLINT NOT NULL CHECK (available IN (0,1)),
  provenance TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS consumption_claims (
  request_id TEXT PRIMARY KEY REFERENCES requests(id),
  owner TEXT NOT NULL,
  started_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS consumption_diagnostics (
  seq BIGSERIAL PRIMARY KEY,
  at BIGINT NOT NULL,
  correlation_id TEXT NOT NULL,
  stage TEXT NOT NULL,
  request_tag TEXT,
  code TEXT NOT NULL,
  http_status INTEGER,
  event_id BIGINT,
  size_bytes INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS consumption_rejections (
  code TEXT PRIMARY KEY,
  first_at BIGINT NOT NULL,
  last_at BIGINT NOT NULL,
  count INTEGER NOT NULL,
  http_status INTEGER,
  size_bytes INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS events (
  seq BIGSERIAL PRIMARY KEY,
  at BIGINT NOT NULL,
  actor TEXT NOT NULL,
  event TEXT NOT NULL,
  request_id TEXT
);
ALTER TABLE requests ADD COLUMN IF NOT EXISTS created_at BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX IF NOT EXISTS sessions_user_expiry_idx ON sessions(user_id, expires);
CREATE INDEX IF NOT EXISTS requests_helper_created_idx ON requests(helper_id, created_at DESC);
CREATE INDEX IF NOT EXISTS requests_buyer_created_idx ON requests(buyer_id, created_at DESC);
CREATE INDEX IF NOT EXISTS challenges_session_kind_idx ON challenges(session_id, kind);
CREATE INDEX IF NOT EXISTS challenges_request_idx ON challenges(request_id);
CREATE INDEX IF NOT EXISTS diagnostics_at_idx ON consumption_diagnostics(at DESC);
`;

function sqliteExecutor(db) {
  const get = (sql, ...args) => db.prepare(sql).get(...args) ?? null;
  const all = (sql, ...args) => db.prepare(sql).all(...args);
  const run = (sql, ...args) => db.prepare(sql).run(...args);
  const event = (actor, name, id = null, at = Date.now()) =>
    run('INSERT INTO events(at,actor,event,request_id) VALUES(?,?,?,?)', at, actor, name, id);
  function expire(now = Date.now()) {
    for (const row of all("SELECT * FROM requests WHERE status IN ('pending','approved')")) {
      if (JSON.parse(row.snapshot).expires_at <= now) {
        run("UPDATE requests SET status='expired',consent_digest=NULL WHERE id=?", row.id);
        run('UPDATE challenges SET used=1 WHERE request_id=?', row.id);
      }
    }
  }
  function request(id) {
    expire();
    const row = get('SELECT * FROM requests WHERE id=?', id);
    ensure(row, 'REQUEST_NOT_FOUND', 404);
    return row;
  }
  return { dialect: 'sqlite', get, all, run, event, expire, request };
}

export function openStore(path) {
  const db = new DatabaseSync(path);
  db.exec(`PRAGMA journal_mode=WAL; PRAGMA synchronous=FULL; PRAGMA foreign_keys=ON;
    PRAGMA busy_timeout=5000;
    CREATE TABLE IF NOT EXISTS users(id TEXT PRIMARY KEY, role TEXT NOT NULL,
      salt TEXT NOT NULL, password_hash TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS trial_invites(token_hash TEXT PRIMARY KEY,
      helper_id TEXT NOT NULL REFERENCES users(id), buyer_id TEXT NOT NULL UNIQUE REFERENCES users(id),
      expires INTEGER NOT NULL, claimed INTEGER);
    CREATE TABLE IF NOT EXISTS credentials(id TEXT PRIMARY KEY, buyer_id TEXT NOT NULL UNIQUE
      REFERENCES users(id), public_key BLOB NOT NULL, counter INTEGER NOT NULL,
      transports TEXT NOT NULL, device_type TEXT NOT NULL, backed_up INTEGER NOT NULL);
    CREATE TABLE IF NOT EXISTS sessions(id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id),
      csrf TEXT NOT NULL, expires INTEGER NOT NULL);
    CREATE TABLE IF NOT EXISTS requests(id TEXT PRIMARY KEY, helper_id TEXT NOT NULL REFERENCES users(id),
      buyer_id TEXT NOT NULL REFERENCES users(id), snapshot TEXT NOT NULL, digest TEXT NOT NULL,
      status TEXT NOT NULL, consent_digest TEXT, consumed_at INTEGER);
    CREATE TABLE IF NOT EXISTS challenges(id TEXT PRIMARY KEY, session_id TEXT NOT NULL,
      buyer_id TEXT NOT NULL, kind TEXT NOT NULL, request_id TEXT, digest TEXT,
      challenge TEXT NOT NULL, expires INTEGER NOT NULL, used INTEGER NOT NULL DEFAULT 0);
    CREATE TABLE IF NOT EXISTS paypal_bindings(request_id TEXT PRIMARY KEY REFERENCES requests(id),
      order_id TEXT NOT NULL UNIQUE, observed_at INTEGER NOT NULL, available INTEGER NOT NULL, provenance TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS consumption_claims(request_id TEXT PRIMARY KEY REFERENCES requests(id),
      owner TEXT NOT NULL, started_at INTEGER NOT NULL);
    CREATE TABLE IF NOT EXISTS consumption_diagnostics(seq INTEGER PRIMARY KEY, at INTEGER NOT NULL,
      correlation_id TEXT NOT NULL, stage TEXT NOT NULL, request_tag TEXT, code TEXT NOT NULL,
      http_status INTEGER, event_id INTEGER, size_bytes INTEGER NOT NULL);
    CREATE TABLE IF NOT EXISTS consumption_rejections(code TEXT PRIMARY KEY, first_at INTEGER NOT NULL,
      last_at INTEGER NOT NULL, count INTEGER NOT NULL, http_status INTEGER, size_bytes INTEGER NOT NULL);
    CREATE TABLE IF NOT EXISTS events(seq INTEGER PRIMARY KEY, at INTEGER NOT NULL,
      actor TEXT NOT NULL, event TEXT NOT NULL, request_id TEXT);`);
  const executor = sqliteExecutor(db);
  function atomic(fn) {
    db.exec('BEGIN IMMEDIATE');
    try { const value = fn(); db.exec('COMMIT'); return value; }
    catch (error) { db.exec('ROLLBACK'); throw error; }
  }
  let transactionTail = Promise.resolve();
  function transaction(fn) {
    const task = transactionTail.then(async () => {
      db.exec('BEGIN IMMEDIATE');
      try {
        const value = await fn(executor);
        db.exec('COMMIT');
        return value;
      } catch (error) {
        db.exec('ROLLBACK');
        throw error;
      }
    });
    transactionTail = task.catch(() => {});
    return task;
  }
  return { ...executor, db, atomic, transaction, ping: async () => true, close: () => db.close() };
}

function postgresPlaceholders(sql) {
  let index = 0;
  return sql.replace(/\?/g, () => `$${++index}`);
}

function postgresExecutor(client) {
  const query = (sql, args = []) => client.query(postgresPlaceholders(sql), args);
  const get = async (sql, ...args) => (await query(sql, args)).rows[0] ?? null;
  const all = async (sql, ...args) => (await query(sql, args)).rows;
  const run = async (sql, ...args) => {
    const result = await query(sql, args);
    return { changes: result.rowCount ?? 0,
      lastInsertRowid: result.rows?.[0]?.seq === undefined ? undefined : Number(result.rows[0].seq) };
  };
  const event = async (actor, name, id = null, at = Date.now()) => {
    const result = await query('INSERT INTO events(at,actor,event,request_id) VALUES(?,?,?,?) RETURNING seq',
      [at, actor, name, id]);
    return { changes: result.rowCount ?? 0, lastInsertRowid: Number(result.rows[0].seq) };
  };
  async function expire(now = Date.now()) {
    const rows = await all("SELECT id,snapshot FROM requests WHERE status IN ('pending','approved')");
    for (const row of rows) {
      if (JSON.parse(row.snapshot).expires_at <= now) {
        await run("UPDATE requests SET status='expired',consent_digest=NULL WHERE id=?", row.id);
        await run('UPDATE challenges SET used=1 WHERE request_id=?', row.id);
      }
    }
  }
  async function request(id) {
    await expire();
    const row = await get('SELECT * FROM requests WHERE id=?', id);
    ensure(row, 'REQUEST_NOT_FOUND', 404);
    return row;
  }
  return { dialect: 'postgres', get, all, run, event, expire, request };
}

export async function openPostgresStore(connectionString, options = {}) {
  ensure(typeof connectionString === 'string' && /^postgres(?:ql)?:\/\//i.test(connectionString),
    'DATABASE_URL_REQUIRED', 503);
  // PostgreSQL BIGINT values in this application are Unix milliseconds or sequence IDs,
  // both safely represented by JavaScript numbers.
  types.setTypeParser(20, value => Number(value));
  const max = options.max ?? Number(process.env.PG_POOL_MAX ?? 4);
  ensure(Number.isInteger(max) && max >= 1 && max <= 8, 'INVALID_DATABASE_POOL_SIZE');
  const pool = new Pool({
    connectionString,
    max,
    idleTimeoutMillis: 10_000,
    connectionTimeoutMillis: 5_000,
    statement_timeout: 7_000,
    query_timeout: 9_000,
    keepAlive: true,
    application_name: 'saysure-staging'
  });
  pool.on('error', () => console.error('PostgreSQL idle connection error.'));
  try {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      await client.query(postgresSchema);
      await client.query('INSERT INTO schema_migrations(version) VALUES(1) ON CONFLICT(version) DO NOTHING');
      await client.query('COMMIT');
    } catch (error) {
      await client.query('ROLLBACK').catch(() => {});
      throw error;
    } finally { client.release(); }
  } catch (error) {
    await pool.end().catch(() => {});
    console.error('PostgreSQL startup or migration failed.');
    throw error;
  }
  const executor = postgresExecutor(pool);
  async function transaction(fn) {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      const value = await fn(postgresExecutor(client));
      await client.query('COMMIT');
      return value;
    } catch (error) {
      await client.query('ROLLBACK').catch(() => {});
      throw error;
    } finally { client.release(); }
  }
  return {
    ...executor,
    transaction,
    expire: now => transaction(tx => tx.expire(now)),
    request: id => transaction(tx => tx.request(id)),
    ping: async () => { await pool.query('SELECT 1 AS ready'); return true; },
    close: () => pool.end()
  };
}
